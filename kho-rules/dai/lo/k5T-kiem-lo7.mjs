const g = (a, b) => (b ? g(b, a % b) : Math.abs(a))
const F = (n, d = 1) => { const k = g(n, d) || 1; return d < 0 ? [-n / k, -d / k] : [n / k, d / k] }
const bang = (a, b) => a[0] * b[1] === b[0] * a[1]
const ps = (x) => (x[1] === 1 ? `${x[0]}` : `\\dfrac{${x[0]}}{${x[1]}}`)
const r6 = (v) => Math.round(v * 1e8) / 1e8
const vn = (v) => String(r6(v)).replace('.', ',')
const pc = (v) => vn(v) + '\\%'
const tim = (lo, hi, f) => { for (let x = lo; x <= hi; x++) if (f(x)) return x; return null }
// dãy cách đều cho bởi số nguyên ×10 (tránh sai số): đầu, cuối, bước (đã ×k)
const day = (dau, cuoi, buoc) => { let n = 0, s = 0; for (let x = dau; x <= cuoi; x += buoc) { n++; s += x } return { n, s } }
// tìm số thập phân x = k/10^m thoả f(x) (vét k)
const timTP = (m, hi, f) => { const q = 10 ** m; for (let k = 0; k <= hi * q; k++) if (f(k / q)) return k / q; return null }

