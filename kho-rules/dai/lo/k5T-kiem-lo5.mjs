// Giá trị trả về là chuỗi, hoặc MẢNG các cách viết tương đương (có một cách khớp là đạt).
const g = (a, b) => (b ? g(b, a % b) : Math.abs(a))
const F = (n, d = 1) => { const k = g(n, d) || 1; return d < 0 ? [-n / k, -d / k] : [n / k, d / k] }
const C = (...xs) => xs.reduce((s, x) => F(s[0] * x[1] + x[0] * s[1], s[1] * x[1]), [0, 1])            // cộng
const T = (a, b) => F(a[0] * b[1] - b[0] * a[1], a[1] * b[1])                                           // trừ
const N = (...xs) => xs.reduce((s, x) => F(s[0] * x[0], s[1] * x[1]), [1, 1])                           // nhân
const D = (a, b) => F(a[0] * b[1], a[1] * b[0])                                                         // chia
const hs = (n, t, m) => F(n * m + t, m), p = (t, m) => F(t, m)
const ps = (x) => (x[1] === 1 ? `${x[0]}` : `\\dfrac{${x[0]}}{${x[1]}}`)
const hon = (x) => { const n = Math.floor(x[0] / x[1]), t = x[0] - n * x[1]; return t ? `${n}\\dfrac{${t}}{${x[1]}}` : `${n}` }
const tp = (x) => { const v = x[0] / x[1]; return Number.isFinite(v) && Math.abs(v * 1e6 - Math.round(v * 1e6)) < 1e-9 && !/e/.test(String(v)) ? String(Math.round(v * 1e6) / 1e6).replace('.', ',') : null }
const PS = (x) => [...new Set([ps(x), hon(x), tp(x)].filter(Boolean))]                                   // mọi cách viết một phân số
const ss = (a, b, nhanA, nhanB) => { const d = a[0] * b[1] - b[0] * a[1]; const [A, B] = [nhanA ?? ps(a), nhanB ?? ps(b)]; return d < 0 ? [`${A}<${B}`, `${B}>${A}`] : d > 0 ? [`${A}>${B}`, `${B}<${A}`] : [`${A}=${B}`, `${B}=${A}`] }
const tim = (lo, hi, f) => { for (let x = lo; x <= hi; x++) if (f(x)) return x; return null }
const timHet = (lo, hi, f) => { const r = []; for (let x = lo; x <= hi; x++) if (f(x)) r.push(x); return r }
const timPS = (f, maxQ = 60, maxP = 4000) => { for (let q = 1; q <= maxQ; q++) for (let pp = 0; pp <= maxP; pp++) { const y = F(pp, q); if (y[1] === q && f(y)) return y } throw new Error('không tìm được phân số') }
const bang = (a, b) => a[0] * b[1] === b[0] * a[1]
const gioPhut = (h) => { const ph = h[0] * 60 / h[1]; return Number.isInteger(ph) ? (ph % 60 ? `${Math.floor(ph / 60)}giờ${ph % 60}phút` : `${ph / 60}giờ`) : null }
const TG = (h) => [...new Set([gioPhut(h), ...PS(h).map((s) => s + 'giờ')].filter(Boolean))]           // thời gian (giờ): "2giờ40phút" | "\dfrac{8}{3}giờ"
const viec = (gio) => D([1, 1], gio)                                                                     // năng suất 1 giờ khi làm hết trong `gio`
// dãy telescoping: tổng các phân số cho bằng danh sách [tử, mẫu]
const tong = (ds) => C(...ds.map(([t, m]) => F(t, m)))

